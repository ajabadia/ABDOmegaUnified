#!/usr/bin/env node
/**
 * check_node_modules_integrity.mjs — Diagnóstico y reparación de `node_modules` corruptos.
 *
 * CONTEXTO (por qué existe este script)
 * -------------------------------------
 * En este checkout apareció un `node_modules` huérfano en la RAÍZ del repo
 * (preexistente, del 30 de julio) con 822 paquetes de los que **226 tenían el
 * `package.json` relleno de bytes nulos**. Turbopack lo tomaba como descripción
 * de paquete y fallaba con `Can't resolve 'tailwindcss'`, dejando el dev server
 * sin CSS. La corrupción viene de una escritura interrumpida (muerte del proceso
 * durante un install, o un Antivirus/ONEDrive que corta el archivo a mitad).
 *
 * Qué detecta, por paquete instalado (incluye `@scope/nombre`):
 *   NULL_BYTES  — el package.json contiene 0x00 (la firma conocida)
 *   EMPTY       — el package.json tiene 0 bytes
 *   BAD_JSON    — no parsea y tampoco tiene bytes nulos (truncado / escritura parcial)
 *
 * Qué NO es corrupción (y por tanto no se reporta):
 *   - Un `node_modules` anidado que no existe: es lo normal, no un error.
 *   - Que un paquete no tenga `package.json`: se salta (no es un paquete).
 *
 * REPARACIÓN — por qué no se "repara" archivo a archivo
 * ---------------------------------------------------
 * Si un `package.json` quedó en ceros es porque el proceso murió DURANTE la
 * escritura del árbol. Es altamente probable que OTROS archivos del mismo
 * paquete estén igual o peor, así que arreglar solo el `package.json` daría
 * un árbol "verde" por el escáner pero roto de verdad. La reparación correcta
 * es delegar en el package manager, que reinstala desde el lockfile:
 *   npm ci · pnpm install --frozen-lockfile · yarn install --immutable
 * `--delete` es la vía quirúrgica: borra SOLO los paquetes corruptos para que
 * el siguiente install los reponga intactos.
 *
 * Uso:
 *   node scripts/check_node_modules_integrity.mjs                 # escanea web/
 *   node scripts/check_node_modules_integrity.mjs --dir <ruta>    # escanea otra ruta
 *   node scripts/check_node_modules_integrity.mjs --json          # reporte JSON
 *   node scripts/check_node_modules_integrity.mjs --delete --yes   # borra los corruptos
 *   node scripts/check_node_modules_integrity.mjs --repair         # reinstala via lockfile
 *   node scripts/check_node_modules_integrity.mjs --self-test      # fixture sintetica
 *
 * Exit 0 = limpio · 1 = corrupción detectada · 2 = error de uso/entorno
 *
 * Standalone: solo Node estándar, sin dependencias. Agnóstico de cwd.
 */
import { readdirSync, readFileSync, statSync, rmSync, mkdirSync, writeFileSync, existsSync, lstatSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PREFIX = '[check_node_modules_integrity]';

/** Profundidad máxima de anidamiento de node_modules que se recorre. */
const MAX_DEPTH = 6;

// ─────────────────────────────────────────────────────────── detección ──

/**
 * Detección común a cualquier fichero de texto: vacío o con bytes nulos.
 *
 * Un fichero sano no tiene ni un solo 0x00, así que la señal es fuerte y sin
 * falsos positivos. Se separa del JSON porque los ficheros de código no se
 * parsean como JSON.
 *
 * @param {Buffer} buf Contenido crudo.
 * @param {boolean} allowEmpty Si false, un fichero de 0 bytes se considera sano.
 * @returns {{code: string, detail: string}|null} null = sano.
 */
function classifyBlob(buf, allowEmpty) {
  if (buf.length === 0) {
    return allowEmpty ? { code: 'EMPTY', detail: '0 bytes' } : null;
  }
  if (buf.includes(0)) {
    const nulls = buf.reduce((n, b) => n + (b === 0 ? 1 : 0), 0);
    return { code: 'NULL_BYTES', detail: `${buf.length} bytes, ${nulls} nulos` };
  }
  return null;
}

/**
 * Clasifica el package.json de un paquete instalado.
 *
 * Exportada para que los tests reutilicen ESTA lógica en vez de reimplementarla:
 * una copia en el test puede desviarse del script y devolver verde sobre un
 * árbol corrupto, que es justo la regresión que se quiere evitar.
 *
 * @param {Buffer} buf Contenido crudo del package.json.
 * @returns {{code: string, detail: string}|null} null = sano.
 */
export function classifyManifest(buf) {
  const base = classifyBlob(buf, true);
  if (base) return base;
  try {
    JSON.parse(buf.toString('utf8'));
    return null;
  } catch (e) {
    return { code: 'BAD_JSON', detail: e.message.slice(0, 80) };
  }
}

/**
 * Ficheros de entrada que se comprueban en la RAÍZ de cada paquete.
 *
 * Solo en la raíz a propósito: `inspectPackage` ya tiene el listado del
 * directorio, así que comprobarlos no cuesta ni una syscall extra. Entradas
 * anidadas (`dist/index.js`, `lib/index.js`) requerirían otro `readdir` por
 * paquete, y la mayoría de los paquetes no las tiene.
 */
const ENTRY_FILES = ['index.js', 'index.mjs', 'index.cjs'];

/**
 * Clasifica el fichero de entrada (index.js) de un paquete.
 *
 * DIFERENCIA IMPORTANTE con `classifyManifest`: aquí un fichero VACÍO se
 * considera SANO por defecto, porque hay paquetes publicados que lo usan a
 * propósito. `client-only@0.0.1` — presente en el lockfile de este repo —
 * publica un `index.js` de 0 bytes como marcador de "solo cliente". Marcarlo
 * como corrupción daría un falso positivo sobre una instalación correcta y
 * `--delete --yes` borraría un paquete sano.
 *
 * Los bytes nulos sí se marcan siempre: ningún fichero JavaScript válido
 * contiene 0x00, así que es la misma firma de escritura interrumpida que
 * hundía los package.json, y aquí no puede ser un falso positivo.
 *
 * @param {Buffer} buf Contenido crudo del fichero de entrada.
 * @param {{allowEmpty?: boolean}} [opts] `allowEmpty` para tratar los 0 bytes
 *   como corrupción. Opcional porque activa falsos positivos conocidos.
 * @returns {{code: string, detail: string}|null} null = sano.
 */
export function classifyEntryFile(buf, opts = {}) {
  return classifyBlob(buf, opts.allowEmpty === true);
}

/**
 * Recorre un `node_modules` y clasifica cada paquete instalado.
 *
 * Optimización deliberada: por paquete hace UNA `readdirSync` del directorio,
 * que devuelve a la vez `package.json` y el posible `node_modules` anidado. La
 * alternativa (statSync del package.json + readdirSync del anidado que
 * normalmente no existe) costaba ~20 s en Windows por los ~750 ENOENT de
 * directorios anidados inexistentes, que además NO son corrupción.
 */
function scanTree(nmDir, corrupt, stats, depth = 0) {
  if (depth > MAX_DEPTH) return;

  let entries;
  try {
    entries = readdirSync(nmDir, { withFileTypes: true });
  } catch {
    // ENOENT: no hay node_modules anidado. Es lo normal, no un error.
    return;
  }

  for (const entry of entries) {
    const name = entry.name;
    if (name === '.bin' || name === '.package-lock.json') continue;

    const full = path.join(nmDir, name);

    // Ámbitos: @scope -> el paquete es un nivel más abajo.
    if (name.startsWith('@')) {
      scanScope(full, corrupt, stats, depth);
      continue;
    }
    inspectPackage(full, name, nmDir, corrupt, stats, depth);
  }
}

/** Itera los paquetes de un ámbito (@babel, @types, ...). */
function scanScope(scopeDir, corrupt, stats, depth) {
  let entries;
  try {
    entries = readdirSync(scopeDir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
    const full = path.join(scopeDir, entry.name);
    inspectPackage(full, `${path.basename(scopeDir)}/${entry.name}`, scopeDir, corrupt, stats, depth);
  }
}

/** Clasifica un paquete y, si tiene árbol anidado, lo recorre. */
function inspectPackage(pkgDir, pkgName, parentDir, corrupt, stats, depth) {
  let listing;
  try {
    listing = readdirSync(pkgDir, { withFileTypes: true });
  } catch {
    return;
  }

  const names = listing.map((e) => e.name);
  const hasManifest = names.includes('package.json');

  if (hasManifest) {
    stats.scanned++;
    let buf;
    try {
      buf = readFileSync(path.join(pkgDir, 'package.json'));
    } catch (e) {
      corrupt.push({ pkg: pkgName, dir: pkgDir, file: 'package.json', code: 'UNREADABLE', detail: e.code || e.message });
      stats.corrupt++;
      return;
    }
    const verdict = classifyManifest(buf);
    if (verdict) {
      corrupt.push({ pkg: pkgName, dir: pkgDir, file: 'package.json', code: verdict.code, detail: verdict.detail });
      stats.corrupt++;
      stats.byCode[verdict.code] = (stats.byCode[verdict.code] || 0) + 1;
    }

    // Ficheros de entrada del paquete. Se reaprovecha el `listing` de arriba:
    // no se llama a readdir ni a stat por cada entrada candidata.
    if (stats.checkEntryFiles) {
      for (const entryName of ENTRY_FILES) {
        if (!names.includes(entryName)) continue;

        // Los symlinks no se siguen: un index.js enlazado fuera del árbol
        // haría que leyéramos (y luego borráramos) el destino equivocado. Se
        // omiten igual que los junctions del resto del script.
        const isLink = listing.find((e) => e.name === entryName)?.isSymbolicLink();
        if (isLink) continue;

        let entryBuf;
        try {
          entryBuf = readFileSync(path.join(pkgDir, entryName));
        } catch {
          // Ausente o ilegible: no es señal de corrupción por sí solo.
          continue;
        }
        const entryVerdict = classifyEntryFile(entryBuf, {
          allowEmpty: stats.allowEmptyEntry === true
        });
        if (entryVerdict) {
          corrupt.push({
            pkg: pkgName,
            dir: pkgDir,
            file: entryName,
            code: entryVerdict.code,
            detail: entryVerdict.detail
          });
          stats.corrupt++;
          stats.byCode[entryVerdict.code] = (stats.byCode[entryVerdict.code] || 0) + 1;
        }
      }
    }
  }

  // Recurse al árbol anidado solo si existe de verdad (evita los ENOENT).
  if (names.includes('node_modules')) {
    scanTree(path.join(pkgDir, 'node_modules'), corrupt, stats, depth + 1);
  }
}

// ───────────────────────────────────────────────────── package manager ──

/** Detecta el package manager de un proyecto por su lockfile. */
function detectPm(projectDir) {
  if (existsSync(path.join(projectDir, 'package-lock.json'))) {
    return { name: 'npm', repair: ['npm', ['ci']] };
  }
  if (existsSync(path.join(projectDir, 'pnpm-lock.yaml'))) {
    return { name: 'pnpm', repair: ['pnpm', ['install', '--frozen-lockfile']] };
  }
  if (existsSync(path.join(projectDir, 'yarn.lock'))) {
    return { name: 'yarn', repair: ['yarn', ['install', '--immutable']] };
  }
  return null;
}

// ───────────────────────────────────────────────────────────── acciones ──

/** Borra los directorios de paquetes corruptos. */
function deleteCorrupt(corrupt, { assumeYes }) {
  // Junction/symlink: rmSync los BORRARÍA como enlace, pero para no arriesgar
  // un rm recursivo que alcance el destino, se|reportan en vez de tocarlos.
  const skipped = [];
  const targets = [];
  for (const c of corrupt) {
    if (c.code === 'UNREADABLE') { skipped.push(c); continue; }
    let isLink = false;
    try { isLink = lstatSync(c.dir).isSymbolicLink(); } catch { /* ya no existe */ }
    if (isLink) skipped.push(c);
    else targets.push(c);
  }

  console.log(`\n${PREFIX} Plan de borrado (${targets.length} paquete(s)):`);
  for (const t of targets.slice(0, 20)) {
    console.log(`  rm ${t.pkg}  [${t.code}]`);
  }
  if (targets.length > 20) console.log(`  ... y ${targets.length - 20} más`);

  if (skipped.length) {
    console.log(`${PREFIX} Omitidos ${skipped.length} (enlaces junctions/symlinks, se reportan):`);
    for (const s of skipped.slice(0, 10)) console.log(`  - ${s.pkg} [${s.code}]`);
  }

  if (!assumeYes) {
    console.log(`\n${PREFIX} Abortado: --delete requiere --yes para ejecutar.`);
    return 0;
  }

  let removed = 0;
  for (const t of targets) {
    try {
      rmSync(t.dir, { recursive: true, force: true });
      removed++;
    } catch (e) {
      console.error(`${PREFIX} ERROR borrando ${t.pkg}: ${e.message}`);
    }
  }
  console.log(`\n${PREFIX} Borrados ${removed}/${targets.length} paquetes corruptos.`);
  console.log(`${PREFIX} Siguiente paso: reinstala desde el lockfile para repobrirlos.`);
  return removed;
}

/** Reinstala el proyecto desde su lockfile (la reparación fiable). */
function repairProject(projectDir) {
  const pm = detectPm(projectDir);
  if (!pm) {
    console.error(`${PREFIX} No encuentro lockfile (package-lock.json / pnpm-lock.yaml / yarn.lock) en ${projectDir}`);
    return 2;
  }
  console.log(`${PREFIX} Reparando con '${pm.repair[0]} ${pm.repair[1].join(' ')}' en ${projectDir}...`);
  console.log(`${PREFIX} ( reinstalla el árbol completo desde el lockfile: la corrupción`);
  console.log(`${PREFIX}   no se limita al package.json, puede afectar a mas archivos )`);
  const res = spawnSync(pm.repair[0], pm.repair[1], { cwd: projectDir, stdio: 'inherit', shell: process.platform === 'win32' });
  if (res.status !== 0) {
    console.error(`${PREFIX} La reparacion fallo (exit ${res.status}).`);
    return res.status ?? 2;
  }
  console.log(`${PREFIX} Reparacion completada. Re-ejecuta el escaner para confirmar.`);
  return 0;
}

// ────────────────────────────────────────────────────────── self-test ──

/** Construye un árbol corrupto sintético y valida detección + reporte. */
function selfTest() {
  const tmp = path.join(os.tmpdir(), `nm-integrity-selftest-${process.pid}`);
  rmSync(tmp, { recursive: true, force: true });
  mkdirSync(tmp, { recursive: true });
  const mk = (rel, content) => {
    const p = path.join(tmp, rel);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, content);
  };

  const nulls = Buffer.alloc(900);
  mk('node_modules/sano/package.json', JSON.stringify({ name: 'sano', version: '1.0.0' }));
  mk('node_modules/nulo/package.json', nulls);                                   // NULL_BYTES
  mk('node_modules/vacio/package.json', '');                                     // EMPTY
  mk('node_modules/truncado/package.json', '{"name":"x","vers');                 // BAD_JSON
  mk('node_modules/@scope/corrupto/package.json', nulls);                         // NULL_BYTES en ámbito
  mk('node_modules/ok2/package.json', JSON.stringify({ name: 'ok2' }));
  mk('node_modules/ok2/node_modules/anidado/package.json', nulls);                 // anidado corrupto
  mk('node_modules/sin-manifest/lib/index.js', 'x');                              // NO es paquete: ignorar

  // --- Ficheros de entrada (index.js y hermanos en la raiz) ---
  mk('node_modules/entrada-buena/package.json', JSON.stringify({ name: 'entrada-buena' }));
  mk('node_modules/entrada-buena/index.js', 'module.exports = 1;');
  mk('node_modules/entrada-nula/package.json', JSON.stringify({ name: 'entrada-nula' }));
  mk('node_modules/entrada-nula/index.js', Buffer.from([0x63, 0x6f, 0x00, 0x00, 0x64, 0x65]));
  mk('node_modules/entrada-vacia-legitima/package.json', JSON.stringify({ name: 'entrada-vacia-legitima' }));
  mk('node_modules/entrada-vacia-legitima/index.js', '');   // patron client-only: SANO
  mk('node_modules/solo-dist/package.json', JSON.stringify({ name: 'solo-dist' }));
  mk('node_modules/solo-dist/dist/index.js', Buffer.from([0, 0, 0])); // anidado: fuera de alcance

  const corrupt = [];
  const stats = {
    scanned: 0, corrupt: 0, byCode: {},
    checkEntryFiles: true,
    allowEmptyEntry: false
  };
  scanTree(path.join(tmp, 'node_modules'), corrupt, stats);

  const found = corrupt.map((c) => c.code).sort();
  const expected = ['BAD_JSON', 'EMPTY', 'NULL_BYTES', 'NULL_BYTES', 'NULL_BYTES', 'NULL_BYTES'];

  let ok = true;
  const check = (label, cond) => {
    console.log(`  ${cond ? 'OK  ' : 'FAIL'} ${label}`);
    if (!cond) ok = false;
  };

  console.log(`${PREFIX} self-test:`);
  check(`6 corruptos detectados (${corrupt.length})`, corrupt.length === 6);
  check('clases correctas', JSON.stringify(found) === JSON.stringify(expected));
  check(`11 package.json saneados (${stats.scanned})`, stats.scanned === 11);
  check('4 con NULL_BYTES', (stats.byCode.NULL_BYTES || 0) === 4);
  check('1 con EMPTY', (stats.byCode.EMPTY || 0) === 1);
  check('1 con BAD_JSON', (stats.byCode.BAD_JSON || 0) === 1);
  check('el paquete sin package.json se ignora', !corrupt.some((c) => c.pkg === 'sin-manifest'));
  check('anidado corrupto detectado', corrupt.some((c) => c.pkg === 'anidado'));
  check('no toca los sanos', !corrupt.some((c) => c.pkg === 'sano' || c.pkg === 'ok2'));
  check('index.js con nulos detectado', corrupt.some((c) => c.pkg === 'entrada-nula' && c.file === 'index.js'));
  check('index.js vacio NO es corrupcion (patron client-only)', !corrupt.some((c) => c.pkg === 'entrada-vacia-legitima'));
  check('index.js sano NO es corrupcion', !corrupt.some((c) => c.pkg === 'entrada-buena'));
  check('dist/index.js fuera de alcance (no se revisa)', !corrupt.some((c) => c.pkg === 'solo-dist'));

  rmSync(tmp, { recursive: true, force: true });
  console.log(ok ? `${PREFIX} self-test OK` : `${PREFIX} self-test FALLIDO`);
  return ok ? 0 : 1;
}

// ────────────────────────────────────────────────────────────────── main ──

function parseArgs(argv) {
  const opts = {
    dirs: [], json: false, del: false, yes: false, repair: false, selfTest: false,
    // Entradas: activo por defecto, salvo que se pida solo package.json.
    entryFiles: true,
    // Los index.js de 0 bytes se consideran sano salvo --strict-empty.
    allowEmptyEntry: false
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dir') opts.dirs.push(argv[++i]);
    else if (a === '--json') opts.json = true;
    else if (a === '--delete') opts.del = true;
    else if (a === '--yes') opts.yes = true;
    else if (a === '--repair') opts.repair = true;
    else if (a === '--self-test') opts.selfTest = true;
    else if (a === '--no-entry-files') opts.entryFiles = false;
    else if (a === '--strict-empty') { opts.allowEmptyEntry = true; opts.entryFiles = true; }
    else if (a === '--help' || a === '-h') opts.help = true;
    else if (a.startsWith('-')) { console.error(`${PREFIX} Opcion desconocida: ${a}`); opts.bad = true; }
    else opts.dirs.push(a);
  }
  if (opts.dirs.length === 0) opts.dirs = [path.join(ROOT, 'web')];
  return opts;
}

const USAGE = `${PREFIX}
  Escanea node_modules buscando package.json corruptos (bytes nulos / vacios / truncados).

  --dir <ruta>   Ruta del proyecto a escanear (por defecto: web/). Repetible.
  --json         Reporte JSON por stdout.
  --delete       Borra los paquetes corruptos (requiere --yes).
  --yes          Confirma el borrado.
  --repair       Reinstala desde el lockfile del proyecto.
  --self-test    Valida el detector contra un arbol sintetico.
  -h, --help     Esta ayuda.

  Exit 0 = limpio · 1 = corrupcion detectada · 2 = error de uso/entorno`;

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) { console.log(USAGE); return 0; }
  if (opts.bad) return 2;
  if (opts.selfTest) return selfTest();
  if (opts.repair && opts.del) {
    console.error(`${PREFIX} --repair y --delete son excluyentes.`);
    return 2;
  }

  if (opts.repair) {
    return repairProject(opts.dirs[0]);
  }

  const corrupt = [];
  const stats = {
    scanned: 0, corrupt: 0, byCode: {},
    checkEntryFiles: opts.entryFiles,
    allowEmptyEntry: opts.allowEmptyEntry
  };
  const roots = [];

  for (const dir of opts.dirs) {
    const projectDir = path.resolve(dir);
    const nmDir = path.join(projectDir, 'node_modules');
    if (!existsSync(nmDir)) {
      if (!opts.json) console.log(`${PREFIX} ${nmDir} no existe, lo salto.`);
      continue;
    }
    roots.push({ projectDir, nmDir });
    if (!opts.json) console.log(`${PREFIX} Escaneando ${nmDir} ...`);
    const before = stats.corrupt;
    const t0 = Date.now();
    scanTree(nmDir, corrupt, stats);
    if (!opts.json) {
      const ms = Date.now() - t0;
      console.log(`${PREFIX}   ${stats.scanned} package.json en ${ms} ms · ${stats.corrupt - before} corruptos`);
    }
  }

  if (opts.json) {
    console.log(JSON.stringify({ roots: roots.map((r) => r.projectDir), scanned: stats.scanned, corrupt }, null, 2));
  } else {
    console.log(`\n${PREFIX} Resumen: ${stats.scanned} package.json revisados, ${corrupt.length} corruptos.`);
    if (corrupt.length) {
      const byCode = {};
      for (const c of corrupt) byCode[c.code] = (byCode[c.code] || 0) + 1;
      for (const [code, n] of Object.entries(byCode)) console.log(`  ${code}: ${n}`);
      console.log(`\n${PREFIX} Primeros 15:`);
      for (const c of corrupt.slice(0, 15)) {
        console.log(`  [${c.code}] ${c.pkg}${c.file ? `/${c.file}` : ''} — ${c.detail}`);
        console.log(`      ${path.relative(ROOT, c.dir)}`);
      }
      if (corrupt.length > 15) console.log(`  ... y ${corrupt.length - 15} más`);

      const pms = roots.map((r) => `${path.relative(ROOT, r.projectDir)}: ${detectPm(r.projectDir)?.name ?? 'sin lockfile'}`);
      console.log(`\n${PREFIX} Repara con:`);
      console.log(`  ${PREFIX} node scripts/check_node_modules_integrity.mjs --repair`);
      console.log(`  ${PREFIX} (pm detectado -> ${pms.join(', ')})`);
      console.log(`  ${PREFIX} O borra solo lo corrupto: --delete --yes`);
    } else {
      console.log(`${PREFIX} OK — ningun node_modules corrupto.`);
    }
  }

  if (corrupt.length && opts.del) {
    return deleteCorrupt(corrupt, { assumeYes: opts.yes }) > 0 ? 0 : 0;
  }

  return corrupt.length > 0 ? 1 : 0;
}

// Solo se ejecuta la CLI cuando el archivo es el entrypoint. Importarlo desde
// un test no debe lanzar el escaneo ni cortar el proceso con process.exit.
const isMainModule =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMainModule) {
  process.exit(main());
}
